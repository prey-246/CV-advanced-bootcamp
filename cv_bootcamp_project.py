def evaluate_comparison(num_samples=10):
    unet_ious = []
    sam_ious = []

    print(f"Evaluating {num_samples} samples...")

    for i, (img, mask) in enumerate(test_images.take(num_samples)):
        # Prep inputs
        raw_img = (img.numpy() * 255).astype(np.uint8)
        gt_mask = (mask.numpy().squeeze() > 0).astype(np.uint8)

        # U-Net Prediction
        u_pred = model.predict(img.numpy()[np.newaxis, ...], verbose=0)
        u_mask = (np.argmax(u_pred[0], axis=-1) > 0).astype(np.uint8)
        unet_ious.append(calculate_iou(u_mask, gt_mask))

        # SAM Prediction (Zero-Shot)
        predictor.set_image(raw_img)
        # Use a 5x5 grid of points for better zero-shot coverage
        s_masks, _, _ = predictor.predict(point_coords=np.array([[64, 64]]), point_labels=np.array([1]), multimask_output=False)
        s_mask = cv2.resize(s_masks[0].astype(np.uint8), (128, 128))
        sam_ious.append(calculate_iou(s_mask, gt_mask))

    print(f"--- Final Capstone Metrics ---")
    print(f"Average U-Net IoU: {np.mean(unet_ious):.4f}")
    print(f"Average SAM IoU: {np.mean(sam_ious):.4f}")

