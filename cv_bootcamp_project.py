"""```markdown
## 3. Traditional Model: U-Net Training
Building and training a standard U-Net for semantic segmentation.
```
"""

def unet_model(output_channels:int):
    inputs = tf.keras.layers.Input(shape=[128, 128, 3])
    # Downsampling
    f1 = layers.Conv2D(64, 3, activation='relu', padding='same')(inputs)
    p1 = layers.MaxPooling2D()(f1)
    # Bottleneck
    b = layers.Conv2D(128, 3, activation='relu', padding='same')(p1)
    # Upsampling
    u1 = layers.UpSampling2D()(b)
    concat = layers.Concatenate()([u1, f1])
    # Output layer
    outputs = layers.Conv2D(output_channels, 3, activation='softmax', padding='same')(concat)
    return tf.keras.Model(inputs=inputs, outputs=outputs)

# Initialize and compile the model
model = unet_model(output_channels=3)
model.compile(optimizer='adam',
              loss='sparse_categorical_crossentropy',
              metrics=['accuracy'])

# Train the model
print("Starting U-Net training...")
model.fit(train_batches, epochs=5, steps_per_epoch=STEPS_PER_EPOCH)
print("U-Net training complete.")

